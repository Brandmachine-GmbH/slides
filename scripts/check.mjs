// The checks a deck has to pass before anything is built from it, in one place so that `slides
// build`, `slides dev`, `slides pdf` and `slides check` cannot disagree about what a valid deck is.
//
//   node scripts/check.mjs [deck] [--warn]   one deck, or every deck when none is named
//
// --warn is for `slides dev`: problems are printed with their file and line and the exit code is
// still 0, so the preview starts and the author fixes them while watching it. `slides build` and
// `slides pdf` run without it and stop, because what they make is the deliverable.
//
// Three things, in this order:
//   1. .slides/names.d.ts, the site's own names (themes, scenes, mockups) as types, so the editor
//      and the typecheck know them. See SlidesSiteNames in src/engine/types.ts.
//   2. The TypeScript check. Vite strips types without checking them, so before this a deck with
//      a misspelt field or a `steps` on a film built and rendered something wrong in silence.
//   3. The shape check: what a type cannot say. At most one title and one end slide, every
//      `type` known, and the names a deck uses actually registered, since the scene names in
//      names.d.ts are the union over every deck.
//
// Everything here is safe to run from several processes at once in one checkout, which is how
// decks get migrated and verified in parallel: names.d.ts is written to a temporary file and
// renamed into place, and the typecheck builds its program in memory rather than writing a
// tsconfig of its own.
import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { build as esbuild } from "esbuild";
import ts from "typescript";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

/** Every value `type` can take, in the order the error messages list them. Mirrors SlideType in
 *  src/engine/types.ts; the typecheck catches a deck the two would disagree about. */
export const SLIDE_TYPES = ["title", "toc", "content", "divider", "plan", "showcase", "viewer", "stack", "scene", "mockup", "film", "end"];
export const KNOWN_TYPES = [...SLIDE_TYPES, "section"];

/** The flags a 0.1 deck used where `type` now goes. Seeing one is how a check knows to say
 *  "migrate this deck" rather than "unknown field". */
const OLD_FLAGS = ["film", "divider", "showcase", "plan", "stack", "viewer", "mockup", "scene", "end"];

const registryKeys = (file) =>
  existsSync(file) ? [...readFileSync(file, "utf8").matchAll(/^\s*"([a-z0-9-]+)"\s*:/gm)].map((m) => m[1]) : [];

/** The names a site defines, read from the files that define them. */
export function siteNames(userRoot) {
  const decksDir = join(userRoot, "decks");
  const themesDir = join(userRoot, "themes");
  const theme = existsSync(themesDir)
    ? readdirSync(themesDir).filter((f) => /^[a-z0-9-]+\.css$/.test(f)).map((f) => f.slice(0, -4)).sort()
    : [];
  const engineScenes = readdirSync(join(root, "src", "engine", "scenes"), { withFileTypes: true })
    .filter((f) => f.isFile() && f.name.endsWith(".tsx"))
    .map((f) => f.name.replace(/\.tsx$/, "").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase());
  const deckScenes = {};
  if (existsSync(decksDir)) {
    for (const d of readdirSync(decksDir, { withFileTypes: true }).filter((e) => e.isDirectory())) {
      deckScenes[d.name] = registryKeys(join(decksDir, d.name, "scenes", "index.ts"));
    }
  }
  const scene = [...new Set([...engineScenes, ...Object.values(deckScenes).flat()])].sort();
  const mockup = registryKeys(join(userRoot, "mockups", "index.ts")).sort();
  return { theme, scene, mockup, engineScenes, deckScenes };
}

/** Write .slides/names.d.ts when it would change. Returns its path. */
export function writeSiteNames(userRoot) {
  const n = siteNames(userRoot);
  const union = (xs) => (xs.length ? xs.map((x) => JSON.stringify(x)).join(" | ") : "never");
  const text =
    "// GENERATED by @brandmachine/slides from themes/, mockups/index.ts and decks/*/scenes/index.ts.\n" +
    "// Every `slides` command that reads decks rewrites it. Do not edit it, and keep .slides/ out of git.\n" +
    "interface SlidesSiteNames {\n" +
    `  theme: ${union(n.theme)};\n` +
    `  scene: ${union(n.scene)};\n` +
    `  mockup: ${union(n.mockup)};\n` +
    "}\n";
  const dir = join(userRoot, ".slides");
  const file = join(dir, "names.d.ts");
  if (existsSync(file) && readFileSync(file, "utf8") === text) return file;
  mkdirSync(dir, { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, text);
  renameSync(tmp, file);
  return file;
}

/** Typecheck the site, or one deck's folder, against the site's tsconfig.json. Returns the
 *  formatted errors, or "" when there are none. A site with no tsconfig.json is not checked
 *  (and says so), since there is nothing to say which compiler options it wants. */
export function typecheck(userRoot, deck) {
  const configPath = join(userRoot, "tsconfig.json");
  if (!existsSync(configPath)) return { skipped: "no tsconfig.json in the site, so decks are not typechecked", errors: "" };
  const read = ts.readConfigFile(configPath, ts.sys.readFile);
  if (read.error) return { errors: ts.formatDiagnostics([read.error], host()) };
  const parsed = ts.parseJsonConfigFileContent(read.config, ts.sys, userRoot);
  const extra = [join(userRoot, ".slides", "names.d.ts"), join(root, "src", "vite-env.d.ts")].filter(existsSync);
  let files;
  if (deck) {
    // One deck's folder: deck.ts and its own scenes. Mockups are left to the whole-site check;
    // a deck cannot change them, and this is what runs before every `slides pdf`.
    const dir = join(userRoot, "decks", deck);
    files = walk(dir).filter((f) => /\.tsx?$/.test(f));
  } else {
    // The decks are added explicitly rather than trusted to the site's `include`: a site whose
    // tsconfig leaves decks/ out would otherwise get no deck typecheck and a message saying
    // every deck passed.
    files = [...parsed.fileNames, ...walk(join(userRoot, "decks")).filter((f) => /\.tsx?$/.test(f))];
  }
  const program = ts.createProgram({ rootNames: [...new Set([...files, ...extra])], options: parsed.options });
  const diags = ts.getPreEmitDiagnostics(program);
  return { errors: diags.length ? ts.formatDiagnosticsWithColorAndContext(diags, host(userRoot)) : "", count: diags.length };
}

function host(cwd = process.cwd()) {
  return { getCanonicalFileName: (f) => f, getCurrentDirectory: () => cwd, getNewLine: () => "\n" };
}

function walk(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((e) => e.isFile())
    .map((e) => join(e.parentPath ?? e.path, e.name));
}

/** A deck.ts as the object it exports. Transpiled to a temp module and imported rather than
 *  pattern-matched, for the reason build.mjs gives at deckMeta. The temp file is per process so
 *  two checks of the same deck cannot remove each other's. */
export async function loadDeck(userRoot, name) {
  const tmpDir = join(userRoot, ".slides", "tmp");
  mkdirSync(tmpDir, { recursive: true });
  const tmp = join(tmpDir, `${name}.${process.pid}.${Date.now()}.mjs`);
  try {
    await esbuild({
      entryPoints: [join(userRoot, "decks", name, "deck.ts")],
      outfile: tmp, bundle: true, format: "esm", platform: "node", logLevel: "silent",
      // The engine types are erased at compile time; nothing else is imported.
      external: ["@engine/*", "@brandmachine/slides"],
    });
    return (await import(pathToFileURL(tmp).href)).default ?? null;
  } finally {
    rmSync(tmp, { force: true });
  }
}

/** Every slide in a deck with where it lives, in deck order: top-level slides and each section's
 *  slides. `section` is the enclosing section, or undefined for a top-level slide. */
export function eachSlide(deck, fn) {
  (deck?.slides ?? []).forEach((item, i) => {
    if (item?.type === "section") {
      fn(item, `slides[${i}]`, undefined, true);
      (item.slides ?? []).forEach((sl, j) => fn(sl, `slides[${i}].slides[${j}]`, item, false));
    } else {
      fn(item, `slides[${i}]`, undefined, false);
    }
  });
}

/** What the types cannot say about a deck. Returns one line per problem, each naming the path in
 *  deck.ts the editor's EDIT lines would use. */
export function shapeProblems(deck, name, names) {
  const out = [];
  const migrate = `this deck is in the 0.1 shape: run  npx slides migrate ${name}`;
  if (!deck || typeof deck !== "object") return [`${name}: deck.ts has no default export`];
  if (!Array.isArray(deck.slides)) {
    return [`${name}: no \`slides\` list${"sections" in deck || "title" in deck ? `; ${migrate}` : ""}`];
  }
  const known = `Known types: ${KNOWN_TYPES.join(", ")}`;
  const typeOf = (sl, where, allowSection) => {
    if (!sl || typeof sl !== "object") { out.push(`${name} ${where}: not a slide`); return null; }
    if (typeof sl.type !== "string") {
      const flag = OLD_FLAGS.find((f) => f in sl) ?? ("headline" in sl ? "content" : null);
      out.push(`${name} ${where}: no \`type\`. ${known}${flag ? `. It looks like a 0.1 slide; ${migrate}` : ""}`);
      return null;
    }
    if (!KNOWN_TYPES.includes(sl.type)) { out.push(`${name} ${where}: unknown type "${sl.type}". ${known}`); return null; }
    if (sl.type === "section" && !allowSection) { out.push(`${name} ${where}: a section inside a section. Sections do not nest.`); return null; }
    return sl.type;
  };
  const count = { title: [], end: [] };
  deck.slides.forEach((item, i) => {
    const t = typeOf(item, `slides[${i}]`, true);
    if (t === "section") {
      if (!Array.isArray(item.slides)) out.push(`${name} slides[${i}]: a section needs a \`slides\` list (it may be empty)`);
      (item.slides ?? []).forEach((sl, j) => {
        const u = typeOf(sl, `slides[${i}].slides[${j}]`, false);
        if (u in count) count[u].push(`slides[${i}].slides[${j}]`);
      });
    } else if (t in count) count[t].push(`slides[${i}]`);
  });
  // One title, because the /admin index takes the deck's name from it and two would make that a
  // guess; one end, because it is where walking the deck forward stops.
  for (const [t, at] of Object.entries(count)) {
    if (at.length > 1) out.push(`${name}: ${at.length} ${t} slides (${at.join(", ")}); a deck has at most one`);
  }
  if (names) {
    const deckScenes = [...names.engineScenes, ...(names.deckScenes[name] ?? [])];
    eachSlide(deck, (sl, where, _sec, isSection) => {
      if (sl?.theme !== undefined && !names.theme.includes(sl.theme)) {
        out.push(`${name} ${where}: theme "${sl.theme}". Known themes: ${names.theme.join(", ") || "(none)"}`);
      }
      if (isSection) return;
      if (sl?.type === "scene" && !deckScenes.includes(sl.name)) {
        out.push(`${name} ${where}: scene "${sl.name}". This deck's scenes: ${deckScenes.join(", ") || "(none)"}`);
      }
      if (sl?.type === "mockup" && !names.mockup.includes(sl.name)) {
        out.push(`${name} ${where}: mockup "${sl.name}". Known mockups: ${names.mockup.join(", ") || "(none)"}`);
      }
    });
    if (deck.theme !== undefined && !names.theme.includes(deck.theme)) {
      out.push(`${name}: theme "${deck.theme}". Known themes: ${names.theme.join(", ") || "(none)"}`);
    }
  }
  return out;
}

/** The whole check for the CLI: names, typecheck, shape. Exits non-zero on any problem, unless
 *  --warn. */
async function main() {
  const userRoot = realpathSync(process.env.SLIDES_ROOT || process.cwd());
  const warn = process.argv.includes("--warn");
  const only = process.argv.slice(2).find((a) => !a.startsWith("--"));
  const mark = warn ? "!" : "✗";
  const after = warn ? "  The preview starts anyway; `slides build` and `slides pdf` will refuse this deck until it is fixed.\n" : "";
  let failed = false;
  const decksDir = join(userRoot, "decks");
  const all = existsSync(decksDir)
    ? readdirSync(decksDir).filter((d) => existsSync(join(decksDir, d, "deck.ts")))
    : [];
  if (only && !all.includes(only)) {
    console.error(`\n  no deck called "${only}". Decks here: ${all.join(", ") || "none"}\n`);
    process.exit(1);
  }
  writeSiteNames(userRoot);
  const names = siteNames(userRoot);

  const tc = typecheck(userRoot, only);
  if (tc.skipped) console.log(`· types: ${tc.skipped}`);
  else if (tc.errors) {
    console.error(`\n${mark} ${tc.count} type error(s) in ${only ? `decks/${only}` : "the site"}\n`);
    console.error(tc.errors);
    console.error(after);
    if (!warn) process.exit(1);
    failed = true;
  } else console.log(`· types: ${only ? `decks/${only}` : "every deck"} typechecks`);

  const problems = [];
  for (const d of only ? [only] : all) {
    // A deck that does not parse is a problem like any other, so `slides dev` still starts on a
    // half-edited deck.ts and Vite's overlay shows the error, instead of a stack trace here.
    try {
      problems.push(...shapeProblems(await loadDeck(userRoot, d), d, names));
    } catch (err) {
      problems.push(`decks/${d}/deck.ts does not load: ${String(err?.message ?? err).split("\n")[0]}`);
    }
  }
  if (problems.length) {
    console.error(`\n${mark} ${problems.length} problem(s) in ${only ? `decks/${only}/deck.ts` : "the decks"}\n`);
    problems.forEach((p) => console.error(`   ${p}`));
    console.error(`\n${after}`);
    if (!warn) process.exit(1);
    return;
  }
  if (failed) return;
  console.log(`· shape: ${only ? only : `${all.length} decks`} ok (${relative(userRoot, join(userRoot, ".slides", "names.d.ts"))} up to date)`);
}

if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
